// Writes `src/data/dimensions.ts` — the pixel size of every clip and still.
// The home page composes cards from real aspect ratios rather than guessing,
// and knowing them up front means no card resizes as its image decodes.
// Run after adding assets:  node scripts/media-manifest.mjs
import { execFileSync } from 'node:child_process'
import { readdirSync, statSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, extname, join } from 'node:path'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const assets = join(root, 'src/assets')
const MEDIA = new Set(['.mp4', '.jpg', '.jpeg', '.png', '.webp'])

const probe = (file) => {
  const out = execFileSync('ffprobe', [
    '-v', 'error', '-select_streams', 'v:0',
    '-show_entries', 'stream=width,height', '-of', 'csv=p=0:s=x', file
  ], { encoding: 'utf8' }).trim().split('\n')[0]
  const [w, h] = out.split('x').map(Number)
  return Number.isFinite(w) && Number.isFinite(h) && w > 0 && h > 0 ? [w, h] : null
}

const entries = []
for (const project of readdirSync(assets).sort()) {
  const dir = join(assets, project)
  if (project === 'posters' || !statSync(dir).isDirectory()) continue
  for (const file of readdirSync(dir).sort()) {
    if (!MEDIA.has(extname(file).toLowerCase())) continue
    const size = probe(join(dir, file))
    if (size) entries.push([`${project}/${file}`, size])
  }
}

const body = entries.map(([id, [w, h]]) => `  '${id}': [${w}, ${h}]`).join(',\n')
writeFileSync(
  join(root, 'src/data/dimensions.ts'),
  `// GENERATED by scripts/media-manifest.mjs — do not edit by hand.\n` +
  `// Pixel size of every asset, keyed "<project-id>/<filename>". Cards are\n` +
  `// composed from these, so nothing has to resize once its image decodes.\n\n` +
  `export const dimensions: Record<string, [number, number]> = {\n${body}\n}\n\n` +
  `export const aspectOf = (id: string) => {\n` +
  `  const size = dimensions[id]\n` +
  `  return size ? size[0] / size[1] : 4 / 3\n` +
  `}\n`
)
console.log(`wrote src/data/dimensions.ts — ${entries.length} assets`)
